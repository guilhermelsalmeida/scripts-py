n = input('Digite algo: ')

# MÉTODO DE TESTE DE TIPO
print(n.isnumeric()) # diz se é possível converter em número inteiro
print(n.isalpha()) # diz se é letra (string)
print(n.isalnum()) # diz se é alfanumérico 
print(n.isupper()) # verifica se só há letras maiúsculas 
print(n.islower()) # verifica se só há letras minúsculas
print(n.isprintable()) # verifica se pode ser impresso 
